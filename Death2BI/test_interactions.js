const assert=require('node:assert/strict'),I=require('./chart-interactions.js'),E=require('./report-engine.js');
const state=new I.ChartInteractions();
const fields=[{table:'Countries',column:'Country',dataField:'_categoryValue',label:'Country'}];
const p={id:'page',visualInteractions:[{source:'chart',target:'ignored',type:'NoFilter'}]};
state.select('report',p.id,'chart',fields,{_categoryValue:'Germany'});
assert.equal(state.filtersFor('report',p,'chart').length,0);
assert.equal(state.filtersFor('report',p,'table').length,1);
assert.equal(state.filtersFor('report',p,'ignored').length,0);
assert.equal(state.filtersFor('other',p,'table').length,0);
assert.equal(state.filtersFor('report',{id:'other'},'table').length,0);
state.select('report',p.id,'chart',fields,{_categoryValue:'France'},true);
assert.equal(state.selected('report',p.id,'chart').tuples.length,2);
state.select('report',p.id,'chart',fields,{_categoryValue:'Germany'},true);
assert.deepEqual(state.selected('report',p.id,'chart').tuples,[['France']]);
state.select('report',p.id,'chart',fields,{_categoryValue:'France'});
assert.equal(state.entries('report',p.id).length,0);
state.select('report',p.id,'chart',fields,{_categoryValue:null});
assert.match(E.parseFilters(state.filtersFor('report',p,'table'))[0].sql,/IS NULL/);
state.clear('report',p.id);assert.equal(state.entries('report',p.id).length,0);
const tuples=[...fields,{table:'Years',column:'Year',dataField:'_dimension',label:'Year'}];
state.select('report',p.id,'chart',tuples,{_categoryValue:'Germany',_dimension:2008});
state.select('report',p.id,'chart',tuples,{_categoryValue:'France',_dimension:2010},true);
const filters=E.parseFilters(state.filtersFor('report',p,'table'));
const model={relationships:[{FromTableName:'Population',FromColumnName:'Country',ToTableName:'Countries',ToColumnName:'Country',IsActive:1,Cardinality:'M:1',CrossFilteringBehavior:'Single'},{FromTableName:'Population',FromColumnName:'Year',ToTableName:'Years',ToColumnName:'Year',IsActive:1,Cardinality:'M:1',CrossFilteringBehavior:'Single'}]};
const sql=E.whereFor('Population',filters,model);assert.match(sql,/ OR /);assert.match(sql,/2008/);assert.match(sql,/2010/);assert.match(sql,/EXISTS/);
assert.equal(state.matchesDatum(state.selected('report',p.id,'chart'),{_categoryValue:'Germany',_dimension:2008}),true);
assert.equal(state.matchesDatum(state.selected('report',p.id,'chart'),{_categoryValue:'Germany',_dimension:2010}),false);
state.removeReport('report');assert.equal(state.entries('report',p.id).length,0);
console.log('PASS: single/toggle/multi selection, clear, source exclusion, NoFilter, report/page isolation, blanks, exact category-series tuples and relationship filters');
