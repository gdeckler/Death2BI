const assert=require('node:assert/strict'),R=require('./vega-renderer'),F=require('./model-formats'),C=require('./report-controls'),Style=require('./report-style');
const lit=x=>({expr:{Literal:{Value:typeof x==='string'?"'"+x+"'":String(x)}}});
const format='+\\$#,0.##;-\\$#,0.##;';
assert.equal(F.text(190000,format,{units:1e6}),'+$0.19M');
assert.equal(F.text(-190000,format,{units:1e6}),'-$0.19M');
assert.equal(F.text(0,format,{units:1e6}),'');
assert.equal(F.text(-1234.56,'\\$#,0.00;(\\$#,0.00);\\$#,0.00'),'($1,234.56)');
assert.equal(F.text(12.3,'0.00 "widgets"'),'12.30 widgets');
assert.equal(F.text(1200000,'0.00,,"M"'),'1.20M');
assert.equal(F.text(.125,'0.0%'),'12.5%');
assert.equal(F.text(12.5,'General'),'12.5');
const spec=R.buildSpec('clusteredBarChart',['Category','Tooltip value','Delta'],[['A',1000000,190000],['B',2000000,-1190000]],['Category','Tooltips','Y'],{formats:['','\\$#,0.00',format],dataLabels:{show:true},model:{theme:{}},visual:{type:'clusteredBarChart',definition:{}}});
assert.equal(spec.data.values.length,2);
assert.deepEqual(spec.data.values.map(x=>x._series),['Delta','Delta']);
assert.deepEqual(spec.data.values.map(x=>x._label),['+$0.19M','-$1.19M']);
assert.equal(spec.data.values[0]._tooltip1,'$1,000,000.00');
assert(spec.layer[0].encoding.tooltip.some(x=>x.title==='Tooltip value'));
const col=table=>({Column:{Expression:{SourceRef:{Entity:table}},Property:'Category'}});
const left={id:'left',type:'slicer',definition:{objects:{selection:[{properties:{singleSelect:lit(true),strictSingleSelect:lit(false)}}]}}};
left.definition.query={queryState:{Values:{projections:[{field:col('Left')}]}}};
const button={id:'button',type:'slicer',originalType:'advancedSlicerVisual',definition:{objects:{selection:[{properties:{strictSingleSelect:lit(true)}}]}}};
button.definition.query={queryState:{Label:{projections:[{field:{Measure:{Property:'Label'}}}]},Values:{projections:[{field:col('Right')}]}}};
assert.equal(C.slicerSettings({},left).single,false);
assert.equal(C.slicerSettings({},button).single,true);
assert.equal(C.slicerSettings({},button).strict,true);
assert.equal(C.slicerSettings({},button).layout,'tiles');
assert.deepEqual(C.field(button),col('Right'));
const page={visuals:[left,button]},get=v=>[v.id+' filter'],allowed=(source,target)=>source==='left'?target==='middle':target==='right';
assert.deepEqual(C.filtersFor({},page,'middle',get,allowed),['left filter']);
assert.deepEqual(C.filtersFor({},page,'right',get,allowed),['button filter']);
assert.deepEqual(C.filtersFor({},page,'left',get,allowed),[]);
console.log('PASS tooltip-only fields, compact signed currency, independent slicer scopes and strict single-select Button slicers');
