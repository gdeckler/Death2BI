const assert=require('node:assert/strict'),R=require('./html-reports.js');
const pages=[{name:'Summary 日本語',html:'<div class="report"><svg><text>12.50%</text></svg></div>'},{name:'Hidden',hidden:true,html:'<table><tr><td>42</td></tr></table>'}];
const html=R.documentFor('Report </title><script>bad()</script>',pages,"@import url('https://example.invalid/font');.report{position:relative;background:url('https://example.invalid/image')}");
assert.ok(html.includes('&lt;/title&gt;'));
assert.ok(html.includes('12.50%'));
assert.ok(html.includes('Hidden (hidden)'));
assert.equal((html.match(/<script[ >]/g)||[]).length,2);
assert.equal((html.match(/<\/script>/g)||[]).length,2);
assert.ok(!html.includes('<script src='));
assert.ok(!html.includes('example.invalid'));
assert.ok(!html.includes('@import'));
const encoded=html.match(/id="death2powerbi-snapshot" type="application\/octet-stream">([^<]+)/)[1];
assert.deepEqual(JSON.parse(Buffer.from(encoded,'base64').toString('utf8')).pages,pages);
assert.throws(()=>R.documentFor('Empty',[],''),/no report pages/);
const isolated=R.isolatedDocument('<script>document.body.textContent="Hello"</script>');
assert.ok(isolated.indexOf('Content-Security-Policy')<isolated.indexOf('<script>'));
assert.ok(R.policy.includes("connect-src 'none'"));
assert.ok(R.policy.includes("frame-src 'none'"));
console.log('PASS: versioned Unicode snapshot, embedded SVG/tables, hidden pages, safe title, standalone scripts and isolated viewer policy');
